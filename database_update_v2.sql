-- 1. Create a table for Website & Extension Error Logging
CREATE TABLE IF NOT EXISTS public.site_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    source TEXT, -- 'website' or 'extension'
    page TEXT,   -- URL or Tab Name
    error_message TEXT,
    stack_trace TEXT,
    user_agent TEXT
);

-- 2. Create a table for Blog Analytics (Read Counts)
CREATE TABLE IF NOT EXISTS public.blog_stats (
    slug TEXT PRIMARY KEY,
    read_count BIGINT DEFAULT 0,
    last_read_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Update medical_codes to support Country targeting
ALTER TABLE public.medical_codes 
ADD COLUMN IF NOT EXISTS country TEXT DEFAULT 'US';

-- 4. Enable Row Level Security (RLS) for public inserts (Logging)
ALTER TABLE public.site_logs ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable insert for all" ON public.site_logs FOR INSERT WITH CHECK (true);

-- 5. Enable RLS for Analytics (Incrementing read counts)
ALTER TABLE public.blog_stats ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable all for everyone" ON public.blog_stats FOR SELECT USING (true);
CREATE POLICY "Enable update for everyone" ON public.blog_stats FOR UPDATE USING (true);
CREATE POLICY "Enable insert for everyone" ON public.blog_stats FOR INSERT WITH CHECK (true);
