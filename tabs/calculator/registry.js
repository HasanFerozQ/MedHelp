  getById(id) {
    return this.calculators.find(c => c.id === id);
  },

  getByRole(roleId) {
    return this.calculators.filter(c => c.role === roleId);
  },

  getImplemented() {
    return this.calculators.filter(c => c.implemented);
  },

  getComingSoon() {
    return this.calculators.filter(c => !c.implemented);
  },

  getFreeDemos() {
    return this.calculators.filter(c => c.freeDemo && c.implemented);
  },

  search(query) {
    const q = query.toLowerCase().trim();
    if (!q) return [];
    const synonyms = {
      'kidney function': ['creatinine', 'egfr', 'crcl'],
      'shock score': ['qsofa', 'sofa'],
      'burn fluid': ['parkland'],
      'heart failure': ['chads'],
      'pe': ['wells'],
      'sepsis': ['qsofa', 'sofa', 'news2']
    };
    let terms = [q];
    for (const [key, vals] of Object.entries(synonyms)) {
      if (q.includes(key) || key.includes(q)) terms = terms.concat(vals);
    }
    return this.calculators.filter(c => {
      const nameEn = (c.name.en || '').toLowerCase();
      const nameEs = (c.name.es || '').toLowerCase();
      const tags = (c.tags || []).join(' ').toLowerCase();
      return terms.some(t => nameEn.includes(t) || nameEs.includes(t) || tags.includes(t));
    });
  }
